export function selectRelevantScenario(
  attributes: AvatarAttributes,
  status: Status,
  career: Career,
  history: GameEvent[]
): ScenarioWithOutcomes | null {
  const playedIds = new Set(history.map((h) => h.scenarioId));
  const available = scenarios.filter((s) => !playedIds.has(s.id));

  if (available.length === 0) {
    return scenarios[Math.floor(Math.random() * scenarios.length)];
  }

  const scored = available.map((scenario) => {
    let score = 0;

    const careerField = career.当前职位.toLowerCase();
    const categoryMap: Record<string, string[]> = {
      '投行': ['投行', 'investment banking', '分析师', '副总裁', '董事'],
      '基金': ['基金', 'fund', '基金经理', '投资', '资管'],
      '银行': ['银行', 'bank', '客户经理', '支行', '信贷'],
      '保险': ['保险', 'insurance', '精算', '理赔'],
      '监管': ['监管', 'regulator', '合规', '央行', '证监会', '银保监'],
      '风控': ['风控', 'risk', '风险管理'],
    };

    for (const [category, keywords] of Object.entries(categoryMap)) {
      if (scenario.category === category) {
        if (keywords.some((kw) => careerField.includes(kw))) {
          score += 10;
        } else {
          score += 3;
        }
      }
    }

    const avgAttr = (
      attributes.品格 +
      attributes.情商 +
      attributes.专业知识 +
      attributes.人脉 +
      attributes.抗压能力
    ) / 5;
    const difficultyDiff = Math.abs(scenario.difficulty - avgAttr / 20);
    score -= difficultyDiff * 2;

    if (status.金钱 < 30 && /金钱|收入|奖金|薪资/.test(scenario.description)) score += 5;
    if (status.心情 < 30 && /压力|焦虑|心理健康/.test(scenario.description)) score += 5;
    if (status.健康 < 30 && /健康|身体|住院/.test(scenario.description)) score += 5;
    if (status.声望 < 30 && /声望|声誉|信任/.test(scenario.description)) score += 5;

    score += Math.random() * 5;

    return { scenario, score };
  });

  scored.sort((a, b) => b.score - a.score);
  return scored[0]?.scenario || available[Math.floor(Math.random() * available.length)];
}

export function selectNextScenario(
  attributes: AvatarAttributes,
  status: Status,
  career: Career,
  history: GameEvent[]
): ScenarioWithOutcomes | null {
  return selectRelevantScenario(attributes, status, career, history);
}
